LXRHorses.Tack = T

-- index by id and by hash for fast lookups
LXRHorses.TackById, LXRHorses.TackByHash = {}, {}
for slot, list in pairs(T) do
    for _, piece in ipairs(list) do
        piece.slot = slot
        if Config and Config.TackOverrides and Config.TackOverrides[piece.id] then
            for k, v in pairs(Config.TackOverrides[piece.id]) do piece[k] = v end
        end
        LXRHorses.TackById[piece.id] = piece
        LXRHorses.TackByHash[piece.hash] = piece
    end
end

function LXRHorses.TackFor(slot, tier)
    local out = {}
    for _, p in ipairs(T[slot] or {}) do if not tier or p.tier <= tier then out[#out + 1] = p end end
    return out
end
